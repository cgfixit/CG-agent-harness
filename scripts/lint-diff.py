#!/usr/bin/env python3
"""Static lint for mistakes that kept reaching review or CI (PRs #742-#810).

Seconds, no compile. Checks what the branch changes against its merge base
with origin/main, reading file content from the working tree:

  CG001 error    added Rust or Python http:// literal without a same-line
                 DevSkim DS137138 annotation (code scanning alerted after
                 push on #770, #788 and on this script's own PR, #812)
  CG002 error    assets/self/MANUAL.md differs from its regenerated bytes
                 (tests/self_manual.rs failed CI on #775)
  CG003 error    changed Markdown file above its DOCS_BUDGET word cap
  CG004 error    DOCS_BUDGET cap raised or row added with no `// why:` above
        warning  ... with one: the raise still needs operator approval
  CG005 warning  added wall-clock assertion bounded under 5 s (runner jitter
                 failed #766, #778 and main)

tests/invariant_guard.rs stays the authority for CG002-CG004; this is the
fast copy. Errors exit 1, warnings exit 0, a bad invocation exits 2.

Usage: python3 scripts/lint-diff.py [--base REF | --staged]
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

GUARD = "tests/invariant_guard.rs"
MANUAL = "assets/self/MANUAL.md"
BUILDER = "scripts/build-self-manual.py"
DEVSKIM_RULE = "DS137138"
# DevSkim DS137138: this pattern in code scope, unless the match itself starts
# with a loopback host (rules/default/security/attack_surface/outbound_network.json).
INSECURE_URL = re.compile(r'http://[^/^\s^"]+')  # DevSkim: ignore DS137138 because this is that rule's own pattern.
LOOPBACK_URL = re.compile(r"http://(localhost|127.0.0.1)")  # DevSkim: ignore DS137138 because this is its loopback exception.
# DevSkim scans every language it knows; these are the two it has alerted on here.
# extension -> (line comment marker, string quote characters)
LANGUAGES = {".rs": ("//", '"'), ".py": ("#", "\"'")}
# DevSkim's own suppression pattern (Suppression.cs). It reads only the first one on a line.
SUPPRESSION = re.compile(r"DevSkim:\s+ignore\s([a-zA-Z\d,:]+)", re.IGNORECASE)
ROW = re.compile(r'^\s*\("([^"]+)",\s*(?:Root|Guide|Evidence|Agent),\s*([0-9_]+)\),')
FOLDER_README_WORDS = re.compile(r"^const FOLDER_README_WORDS: usize = ([0-9_]+);", re.M)
ELAPSED_BOUND = re.compile(r"elapsed\(\)\s*<=?\s*(?:[A-Za-z_:]*::)?Duration::from_(millis|secs)\(\s*([0-9_]+)\s*\)")
TIMING_FLOOR_MS = 5000
HUNK = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@")


def git(*args, check=True):
    done = subprocess.run(["git", *args], capture_output=True, text=True, encoding="utf-8", errors="replace", check=False)
    if check and done.returncode != 0:
        sys.stderr.write(done.stderr)
        sys.exit(2)
    return done.stdout


def added_lines(diff_args):
    """{path: {line number: text}} for every line the diff adds."""
    out = git("diff", "--no-color", "--no-ext-diff", "--no-renames", "--diff-filter=AM", "-U0", *diff_args)
    added, path, line = {}, None, 0
    for raw in out.splitlines():
        if raw.startswith("+++ "):
            path = raw[6:] if raw.startswith("+++ b/") else None
            continue
        hunk = HUNK.match(raw)
        if hunk:
            line = int(hunk.group(1))
            continue
        if path and raw.startswith("+") and not raw.startswith("+++"):
            added.setdefault(path, {})[line] = raw[1:]
            line += 1
    return added


def language(path):
    return LANGUAGES.get(os.path.splitext(path)[1])


def code_part(line, marker="//", quotes='"'):
    """The line without its trailing comment. `://` inside a URL is not a `//`
    comment start, and a marker inside a string literal is skipped when the
    string opens on this line."""
    closing, i = None, 0
    while i < len(line):
        ch = line[i]
        if closing:
            if ch == "\\":
                i += 2
                continue
            if ch == closing:
                closing = None
        elif ch in quotes:
            closing = ch
        elif line.startswith(marker, i) and (marker != "//" or i == 0 or line[i - 1] != ":"):
            return line[:i]
        i += 1
    return line


def suppressed(line):
    """DevSkim honours the first suppression on the line, wherever it sits
    (inside a string too), and ignores any later one."""
    first = SUPPRESSION.search(line)
    return bool(first) and bool({DEVSKIM_RULE.lower(), "all"} & set(first.group(1).lower().split(",")))


def insecure_urls(line, marker="//", quotes='"'):
    """Insecure-URL matches DevSkim would report on this line."""
    if suppressed(line):
        return []
    code = code_part(line, marker, quotes)
    return [m.group(0) for m in INSECURE_URL.finditer(code) if not LOOPBACK_URL.match(m.group(0))]


def budget_rows(text):
    """{path: (cap, line index)} from the DOCS_BUDGET table."""
    rows, inside = {}, False
    for index, line in enumerate(text.splitlines()):
        if line.startswith("const DOCS_BUDGET:"):
            inside = True
        elif inside and line.startswith("];"):
            break
        elif inside:
            row = ROW.match(line)
            if row:
                rows[row.group(1)] = (int(row.group(2).replace("_", "")), index)
    return rows


def why_lines_above(lines, index):
    """Line indexes of the comment block directly above a row that say why."""
    found, at = [], index - 1
    while at >= 0 and lines[at].lstrip().startswith("//"):
        if "why:" in lines[at]:
            found.append(at)
        at -= 1
    return found


def cap_for(path, rows, folder_words):
    if path in rows:
        return rows[path][0]
    if path.endswith("/README.md"):
        return folder_words
    return None


class Report:
    def __init__(self):
        self.errors = 0
        self.warnings = 0
        self.github = os.environ.get("GITHUB_ACTIONS") == "true"

    def add(self, level, code, path, line, message):
        if level == "error":
            self.errors += 1
        else:
            self.warnings += 1
        where = f"{path}:{line}" if line else path
        print(f"{where}: {level} {code}: {message}")
        if self.github:
            spot = f"file={path},line={line}" if line else f"file={path}"
            escaped = message.replace("%", "%25").replace("\n", "%0A")
            print(f"::{level} {spot},title={code}::{escaped}")


def check_devskim(report, added):
    for path, lines in sorted(added.items()):
        if not language(path):
            continue
        marker, quotes = language(path)
        for number, text in sorted(lines.items()):
            for url in insecure_urls(text, marker, quotes):
                report.add(
                    "error", "CG001", path, number,
                    f"`{url}` needs `{marker} DevSkim: ignore {DEVSKIM_RULE} because <reason>` at the end of this "
                    "same line (a comment on the line above does not count here), or an https:// URL.",
                )


def check_self_manual(report, root):
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, "MANUAL.md")
        done = subprocess.run(
            [sys.executable, os.path.join(root, BUILDER), "--root", root, "--out", out],
            capture_output=True, text=True, check=False,
        )
        if done.returncode != 0:
            report.add("error", "CG002", BUILDER, 0, f"the generator failed: {done.stderr.strip()[-300:]}")
            return
        with open(out, "rb") as fresh, open(os.path.join(root, MANUAL), "rb") as tracked:
            if fresh.read() != tracked.read():
                report.add(
                    "error", "CG002", MANUAL, 0,
                    f"stale: an input changed. Run `python3 {BUILDER}` and commit the result.",
                )


def check_docs_budget(report, root, changed, guard_text):
    rows = budget_rows(guard_text)
    folder = FOLDER_README_WORDS.search(guard_text)
    folder_words = int(folder.group(1).replace("_", "")) if folder else None
    for path in sorted(changed):
        if not path.lower().endswith((".md", ".markdown", ".mdx")):
            continue
        cap = cap_for(path, rows, folder_words)
        full = os.path.join(root, path)
        if cap is None or not os.path.isfile(full):
            continue
        with open(full, encoding="utf-8", errors="replace") as handle:
            words = len(handle.read().split())
        if words > cap:
            report.add("error", "CG003", path, 0, f"{words} words, cap {cap} in {GUARD} DOCS_BUDGET. Trim it; do not raise the cap.")


def check_cap_raises(report, base, guard_text, guard_added):
    old = git("show", f"{base}:{GUARD}", check=False)
    if not old:
        return
    before, lines = budget_rows(old), guard_text.splitlines()
    for path, (cap, index) in sorted(budget_rows(guard_text).items()):
        was = before.get(path, (None, 0))[0]
        if was is not None and cap <= was:
            continue
        change = f"raised from {was} to {cap}" if was is not None else f"new row at {cap}"
        fresh_why = [at for at in why_lines_above(lines, index) if at + 1 in guard_added]
        if fresh_why:
            report.add("warning", "CG004", GUARD, index + 1, f"`{path}` cap {change}: needs operator approval; name it in the PR body.")
        else:
            report.add("error", "CG004", GUARD, index + 1, f"`{path}` cap {change} with no new `// why:` comment directly above the row.")


def check_timing(report, added):
    for path, lines in sorted(added.items()):
        if not path.endswith(".rs"):
            continue
        for number, text in sorted(lines.items()):
            bound = ELAPSED_BOUND.search(code_part(text))
            if not bound or re.match(r"\s*while\b", text):
                continue
            value = int(bound.group(2).replace("_", ""))
            millis = value if bound.group(1) == "millis" else value * 1000
            if millis < TIMING_FLOOR_MS:
                report.add(
                    "warning", "CG005", path, number,
                    f"{millis} ms wall-clock bound: a busy runner fails it. Assert order or causality, or move "
                    "the bound an order of magnitude from the expected time.",
                )


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    scope = parser.add_mutually_exclusive_group()
    scope.add_argument("--base", help="compare against this ref (default: merge base with origin/main)")
    scope.add_argument("--staged", action="store_true", help="check what is staged for the next commit")
    args = parser.parse_args()

    root = git("rev-parse", "--show-toplevel").strip()
    os.chdir(root)
    if args.staged:
        base, diff_args = "HEAD", ["--cached"]
    else:
        ref = args.base or "origin/main"
        base = git("merge-base", ref, "HEAD", check=False).strip()
        if not base:
            sys.stderr.write(f"lint-diff: no merge base with {ref}; fetch it or pass --base REF.\n")
            return 2
        diff_args = [base]

    added = added_lines(diff_args)
    changed = set(git("diff", "--name-only", "--no-renames", "--diff-filter=AM", *diff_args).split("\n")) - {""}
    if not args.staged:
        # `git diff` cannot see a file that was never added; it is still part of the branch.
        for path in git("ls-files", "--others", "--exclude-standard").splitlines():
            changed.add(path)
            if language(path):
                with open(os.path.join(root, path), encoding="utf-8", errors="replace") as handle:
                    added[path] = dict(enumerate(handle.read().splitlines(), 1))
    with open(os.path.join(root, GUARD), encoding="utf-8") as handle:
        guard_text = handle.read()

    report = Report()
    check_devskim(report, added)
    check_self_manual(report, root)
    check_docs_budget(report, root, changed, guard_text)
    check_cap_raises(report, base, guard_text, added.get(GUARD, {}))
    check_timing(report, added)
    print(f"lint-diff: {report.errors} error(s), {report.warnings} warning(s) against {base[:12]}")
    return 1 if report.errors else 0


if __name__ == "__main__":
    sys.exit(main())
