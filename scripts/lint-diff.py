#!/usr/bin/env python3
"""Static lint for mistakes that kept reaching review or CI (PRs #742-#810).

Seconds, no compile. Checks what the branch changes against its merge base
with origin/main, reading file content from the working tree. With --staged
it checks the pending commit instead: staged lines, and file content from an
index snapshot, so unstaged edits neither hide nor cause a finding.

  CG001 error    added Rust or Python http:// literal without a same-line
                 DevSkim DS137138 annotation (code scanning alerted after
                 push on #770, #788 and on this script's own PR, #812)
  CG002 error    assets/self/MANUAL.md differs from its regenerated bytes
                 (tests/self_manual.rs failed CI on #775)
  CG003 error    changed Markdown file above its DOCS_BUDGET word cap
  CG004 error    DOCS_BUDGET cap raised or row added with no `// why:` above
        warning  ... with one: the raise still needs operator approval
  CG005 warning  added wall-clock assertion bounded under 5 s (runner jitter
                 failed #766, #778 and main)
  CG006 warning  added weak-hash name without a same-line DevSkim DS126858
                 suppression (alerted after push twice on #885)
  CG011 error    added assert/panic/expect message that prints a response body
                 or credential (CodeQL rust/cleartext-logging alerted after
                 push on #1036's alert #1094 and on #1096-#1100, #1102, fixed
                 in bee4525): a name bound by `let (status, name) =` in the
                 file from a helper that sends a cookie (as_account), or
                 `cookie`, `token`, `secret`, `password` and kin. Use fixed text naming the step; `status` may stay.
                 An exception ends its own line with
                 `// lint-diff: allow CG011 until YYYY-MM-DD approved by <who>: <why>`
                 and stops counting on that date.
  CG010 warning  added Rust string literal passed to a password hasher or
                 bound to a password-named variable (CodeQL
                 rust/hard-coded-cryptographic-value alerted after push on
                 #1034 and #1035; mint test passwords per run instead)
  CG008 error    deleted Markdown file still in DOCS_BUDGET_OWNER_EXEMPT
                 (invariant_guard fails; #881 broke main and the branches
                 that merged it until #888) or in the self-manual INPUTS
        warning  ... still has a DOCS_BUDGET row (dead, not a CI failure),
                 or another tracked file still names it
  CG009 error    Markdown says a full config key ships a value that
                 assets/config.default.yaml does not (browser.enabled after
                 #887, fixed in 49db7bf; #785; #66; the config-guard skill
                 that #960 fixes); checked on added Markdown lines, and on
                 every Markdown file for each key whose shipped value the
                 diff changes
        warning  ... the same, for a key named by a unique suffix
                 (`result_reads.arxiv_pdf`); a claim the config cannot
                 confirm (unknown key, mapping, null, other type) is skipped

tests/invariant_guard.rs stays the authority for CG002-CG004 and CG008's
exempt entries; this is the fast copy. CG006 is a warning: its pattern comes
from the alerts above, not from DevSkim's rule files. Hex-digest literals
(DS173237) are not linted: 24 unsuppressed runs on main drew no open alert,
so a pattern built from the alerts would flag lines DevSkim does not.
Errors exit 1, warnings exit 0, a bad invocation exits 2.

Usage: python3 scripts/lint-diff.py [--base REF | --staged]
"""
import argparse
import datetime
import os
import re
import subprocess
import sys
import tempfile

GUARD = "tests/invariant_guard.rs"
MANUAL = "assets/self/MANUAL.md"
BUILDER = "scripts/build-self-manual.py"
DEVSKIM_RULE = "DS137138"
WEAK_HASH_RULE = "DS126858"
# DevSkim DS137138: this pattern in code scope, unless the match itself starts
# with a loopback host (rules/default/security/attack_surface/outbound_network.json).
INSECURE_URL = re.compile(r'http://[^/^\s^"]+')  # DevSkim: ignore DS137138 because this is that rule's own pattern.
LOOPBACK_URL = re.compile(r"http://(localhost|127.0.0.1)")  # DevSkim: ignore DS137138 because this is its loopback exception.
# DevSkim scans every language it knows; these are the two it has alerted on here.
# extension -> (line comment marker, string quote characters)
LANGUAGES = {".rs": ("//", '"'), ".py": ("#", "\"'")}
# CG006 also covers shell (the #885 alerts were in uninstall-macos.sh) and
# JavaScript; CG001 keeps its two languages.
DIGEST_LANGUAGES = {**LANGUAGES, ".sh": ("#", "\"'"), ".mjs": ("//", "\"'`"), ".js": ("//", "\"'`")}
WEAK_HASH = re.compile(r"\b(?:sha-?1|md5)\b", re.IGNORECASE)  # DevSkim: ignore DS126858 because this is that rule's own pattern.
# CG010: the sinks CodeQL's hard-coded-cryptographic-value query followed from a
# test literal here (#1034's alert #1093), and the binding that fed one.
PASSWORD_LITERAL = re.compile(
    r'\b(?:hash_password(?:_with_salt)?|hash_bootstrap_password|verify_password)\(\s*"'
    r'|\blet\s+(?:mut\s+)?\w*(?:password|passwd|passphrase)\w*\s*(?::\s*&(?:\'static\s+)?str\s*)?=\s*"',
    re.IGNORECASE,
)
# CG011: a macro whose message reaches the test log, the names that hold a
# response body or credential, and how an exception is spelled.
ASSERT_MACRO = re.compile(
    r"\b(?:debug_)?assert(?:_eq|_ne)?!\s*\(|\b(?:panic|unreachable|todo|unimplemented)!\s*\(|\.expect\("
)
INTERPOLATED = re.compile(r"\{(\w+)(?::[^{}]*)?\}")
POSITIONAL = re.compile(r"\{(?::[^{}]*)?\}")
RESPONSE_TUPLE = re.compile(
    r"\blet\s+\(\s*(?:status|status_code|code|st)\s*,\s*(?:mut\s+)?(\w+)\s*\)\s*=\s*(\w+)\s*\("
)
HELPER_FN = re.compile(r"^\s*(?:pub(?:\([a-z]+\))?\s+)?(?:async\s+)?fn\s+(\w+)", re.M)
SECRET_NAMES = frozenset({
    "cookie", "cookies", "token", "secret", "password", "passwd", "api_key", "bearer", "authorization",
})
ALLOW_CG011 = re.compile(r"lint-diff:\s*allow\s+CG011\s+until\s+(\d{4}-\d{2}-\d{2})\s+approved by\s+\S[^:]*:\s*\S")
# DevSkim's own suppression pattern (Suppression.cs). It reads only the first one on a line.
SUPPRESSION = re.compile(r"DevSkim:\s+ignore\s([a-zA-Z\d,:]+)", re.IGNORECASE)
# One table entry. rustfmt breaks a row wider than max_width over several lines
# and adds a trailing comma, so whitespace here includes newlines.
ROW = re.compile(r'\(\s*"([^"]+)",\s*(?:Root|Guide|Evidence|Agent),\s*([0-9_]+),?\s*\)')
STRING = re.compile(r'"[^"]*"')
EXEMPT_TABLE = re.compile(r"^const DOCS_BUDGET_OWNER_EXEMPT:[^=]*=\s*&\[(.*?)\];", re.M | re.S)
EXEMPT_ENTRY = re.compile(r'\(\s*"([^"]+)"\s*,')
FOLDER_README_WORDS = re.compile(r"^const FOLDER_README_WORDS: usize = ([0-9_]+);", re.M)
ELAPSED_BOUND = re.compile(r"elapsed\(\)\s*<=?\s*(?:[A-Za-z_:]*::)?Duration::from_(millis|secs)\(\s*([0-9_]+)\s*\)")
TIMING_FLOOR_MS = 5000
MARKDOWN = (".md", ".markdown", ".mdx")
HUNK = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@")


def git(*args, check=True):
    done = subprocess.run(["git", *args], capture_output=True, text=True, encoding="utf-8", errors="replace", check=False)
    if check and done.returncode != 0:
        sys.stderr.write(done.stderr)
        sys.exit(2)
    return done.stdout


def added_lines(diff_args):
    """{path: {line number: text}} for every line the diff adds."""
    out = git("diff", "--no-color", "--no-ext-diff", "--no-renames", "--diff-filter=AM", "-U0", *diff_args)
    return parse_added(out)


def parse_added(out):
    """added_lines for one `git diff -U0` text. A hunk header says how many
    lines it adds, and that many `+` lines are content whatever they start
    with: an added line `++ note` reads `+++ note` in the diff, which is not
    the next file's header and must not end this file's findings."""
    added, path, line, left = {}, None, 0, 0
    for raw in out.splitlines():
        if left and raw.startswith("+"):
            if path:
                added.setdefault(path, {})[line] = raw[1:]
            line += 1
            left -= 1
            continue
        if raw.startswith("+++ "):
            path = raw[6:] if raw.startswith("+++ b/") else None
            continue
        hunk = HUNK.match(raw)
        if hunk:
            line = int(hunk.group(1))
            left = int(hunk.group(2)) if hunk.group(2) is not None else 1
    return added


def language(path):
    return LANGUAGES.get(os.path.splitext(path)[1])


def code_part(line, marker="//", quotes='"'):
    """The line without its trailing comment. `://` inside a URL is not a `//`
    comment start, and a marker inside a string literal is skipped when the
    string opens on this line."""
    closing, i = None, 0
    while i < len(line):
        ch = line[i]
        if closing:
            if ch == "\\":
                i += 2
                continue
            if ch == closing:
                closing = None
        elif ch in quotes:
            closing = ch
        elif line.startswith(marker, i) and (marker != "//" or i == 0 or line[i - 1] != ":"):
            return line[:i]
        i += 1
    return line


def suppressed(line, rule=DEVSKIM_RULE):
    """DevSkim honours the first suppression on the line, wherever it sits
    (inside a string too), and ignores any later one."""
    first = SUPPRESSION.search(line)
    return bool(first) and bool({rule.lower(), "all"} & set(first.group(1).lower().split(",")))


def weak_hashes(line, marker="//", quotes='"'):
    """Weak-hash names CG006 reports on one line: code and strings, not comments."""
    if suppressed(line, WEAK_HASH_RULE):
        return []
    return [m.group(0) for m in WEAK_HASH.finditer(code_part(line, marker, quotes))]


def insecure_urls(line, marker="//", quotes='"'):
    """Insecure-URL matches DevSkim would report on this line."""
    if suppressed(line):
        return []
    code = code_part(line, marker, quotes)
    return [m.group(0) for m in INSECURE_URL.finditer(code) if not LOOPBACK_URL.match(m.group(0))]


def budget_table(text):
    """(rows, unparsed): {path: (cap, line index of the row's opening)} from
    the DOCS_BUDGET table, and how many of its entries the pattern missed.
    Each entry holds exactly one string, its path, so a string count that
    differs from the row count means a row format this lint cannot read."""
    lines = text.splitlines()
    start = next((i for i, line in enumerate(lines) if line.startswith("const DOCS_BUDGET:")), None)
    if start is None:
        return {}, 0
    end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("];")), len(lines))
    body = "\n".join("" if line.lstrip().startswith("//") else line for line in lines[start + 1:end])
    rows = {}
    for row in ROW.finditer(body):
        rows[row.group(1)] = (int(row.group(2).replace("_", "")), start + 1 + body.count("\n", 0, row.start()))
    return rows, len(STRING.findall(body)) - len(rows)


def budget_rows(text):
    return budget_table(text)[0]


def why_lines_above(lines, index):
    """Line indexes of the comment block directly above a row that say why."""
    found, at = [], index - 1
    while at >= 0 and lines[at].lstrip().startswith("//"):
        if "why:" in lines[at]:
            found.append(at)
        at -= 1
    return found


def cap_for(path, rows, folder_words):
    if path in rows:
        return rows[path][0]
    if path.endswith("/README.md"):
        return folder_words
    return None


class Report:
    def __init__(self):
        self.errors = 0
        self.warnings = 0
        self.github = os.environ.get("GITHUB_ACTIONS") == "true"

    def add(self, level, code, path, line, message):
        if level == "error":
            self.errors += 1
        else:
            self.warnings += 1
        where = f"{path}:{line}" if line else path
        print(f"{where}: {level} {code}: {message}")
        if self.github:
            spot = f"file={path},line={line}" if line else f"file={path}"
            escaped = message.replace("%", "%25").replace("\n", "%0A")
            print(f"::{level} {spot},title={code}::{escaped}")


def check_devskim(report, added):
    for path, lines in sorted(added.items()):
        if not language(path):
            continue
        marker, quotes = language(path)
        for number, text in sorted(lines.items()):
            for url in insecure_urls(text, marker, quotes):
                report.add(
                    "error", "CG001", path, number,
                    f"`{url}` needs `{marker} DevSkim: ignore {DEVSKIM_RULE} because <reason>` at the end of this "
                    "same line (a comment on the line above does not count here), or an https:// URL.",
                )


def check_weak_hashes(report, added):
    for path, lines in sorted(added.items()):
        syntax = DIGEST_LANGUAGES.get(os.path.splitext(path)[1])
        if not syntax:
            continue
        marker, quotes = syntax
        for number, text in sorted(lines.items()):
            for found in weak_hashes(text, marker, quotes):
                report.add(
                    "warning", "CG006", path, number,
                    f"`{found}` is what DevSkim {WEAK_HASH_RULE} alerts on after push. If it names a protocol "
                    f"label or item ID, not integrity hashing, end this same line with "
                    f"`{marker} DevSkim: ignore {WEAK_HASH_RULE} because <reason>`; otherwise use SHA-256.",
                )


def password_literals(line):
    """CG010 matches on one Rust line: code and strings, not comments."""
    return [m.group(0) for m in PASSWORD_LITERAL.finditer(code_part(line))]


def check_password_literals(report, added):
    for path, lines in sorted(added.items()):
        if not path.endswith(".rs"):
            continue
        for number, text in sorted(lines.items()):
            if password_literals(text):
                report.add(
                    "warning", "CG010", path, number,
                    "a string literal reaches a password hasher or password binding; CodeQL "
                    "rust/hard-coded-cryptographic-value alerts on it after push. Mint it per run "
                    "(`crate::common::random_urlsafe(24)` or `authn::new_session_id()`).",
                )


def message_leaks(lines, index, bound, today):
    """CG011 on lines[index]: names an assert/panic/expect message prints that
    hold a response body from a credentialed helper, or a credential. `bound`
    is the file's names bound by `let (status, name) = helper(`. A macro opened on an earlier line still counts
    while its parentheses are open; an expired or unapproved allow does not."""
    line = lines[index]
    code = code_part(line)
    opened = False
    for at in range(index, max(-1, index - 9), -1):
        found = ASSERT_MACRO.search(code_part(lines[at]))
        if not found:
            continue
        if at == index:
            opened = True
        else:
            # Only the macro's own parenthesis counts: later lines open and close others.
            span = STRING.sub('""', "\n".join([lines[at][found.end() - 1:]] + lines[at + 1:index]))
            depth = 0
            for ch in span:
                depth += (ch == "(") - (ch == ")")
                if depth == 0:
                    break
            opened = depth > 0
        break
    if not opened:
        return []
    allow = ALLOW_CG011.search(line)
    if allow and allow.group(1) >= today.isoformat():
        return []
    literals = STRING.findall(code)
    names = {name for literal in literals for name in INTERPOLATED.findall(literal)}
    if any(POSITIONAL.search(literal) for literal in literals):
        names.update(re.findall(r"[A-Za-z_]\w*", code[code.rfind('"') + 1:]))
    return sorted(name for name in names if name in SECRET_NAMES or name in bound)


def credentialed_bodies(text):
    """Names a file binds as the body of a helper that sends a credential: a
    helper fn of this file whose own text mentions a cookie (`as_account`,
    which CodeQL followed from the session cookie to the message). Bodies of
    helpers that send none are printed all over the tests and are not linted."""
    starts = [(m.start(), m.group(1)) for m in HELPER_FN.finditer(text)]
    helpers = {
        name for i, (start, name) in enumerate(starts)
        if "cookie" in text[start:(starts[i + 1][0] if i + 1 < len(starts) else len(text))].lower()
    }
    return {name for name, helper in RESPONSE_TUPLE.findall(text) if helper in helpers}


def check_assert_messages(report, added, read, today=None):
    today = today or datetime.date.today()
    for path, numbered in sorted(added.items()):
        if not path.endswith(".rs"):
            continue
        lines = read(path).splitlines()
        bound = credentialed_bodies("\n".join(lines))
        for number in sorted(numbered):
            if number > len(lines):
                continue
            for name in message_leaks(lines, number - 1, bound, today):
                report.add(
                    "error", "CG011", path, number,
                    f"this assert/panic message prints `{name}`, a response body or credential; CodeQL "
                    "rust/cleartext-logging alerts on it after push (#1096-#1102). Use fixed text naming the "
                    "step and keep `status` (as bee4525 did). A reviewed exception ends the line with "
                    "`// lint-diff: allow CG011 until YYYY-MM-DD approved by <who>: <why>`.",
                )


def self_manual_inputs(text):
    inputs = re.search(r"^INPUTS = \[(.*?)^\]", text, re.M | re.S)
    return {literal[1:-1] for literal in STRING.findall(inputs.group(1))} if inputs else set()


def owner_exempt_paths(text):
    """Paths in DOCS_BUDGET_OWNER_EXEMPT, skipping commented-out lines."""
    table = EXEMPT_TABLE.search(text)
    if not table:
        return set()
    body = "\n".join(line for line in table.group(1).splitlines() if not line.lstrip().startswith("//"))
    return set(EXEMPT_ENTRY.findall(body))


def reference_needle(path, tracked):
    """The text a reference to deleted `path` still carries.

    A folder index (`README.md`) is named by its folder path. A file whose
    basename another tracked file shares (`SKILL.md`) is named by its own folder
    (`doc-sync/`): its bare basename would match every mention of a namesake.
    Any other doc is named by its file name, which relative links keep. An empty
    needle (a root index) names nothing.
    """
    base, folder = os.path.basename(path), os.path.dirname(path)
    if base.lower() == "readme.md":
        return folder + "/" if folder else ""
    if any(os.path.basename(other) == base for other in tracked if other != path):
        return os.path.basename(folder) + "/" if folder else ""
    return base


def check_deleted_docs(report, deleted, guard_text, builder_text, references, tracked=()):
    """`references(needle)` lists tracked files whose content contains `needle`;
    `tracked` lists the paths that remain, to tell a shared basename."""
    rows = budget_rows(guard_text)
    remaining = [other for other in tracked if other not in deleted]
    exempt = owner_exempt_paths(guard_text)
    inputs = self_manual_inputs(builder_text)
    for path in sorted(deleted):
        if not path.lower().endswith(MARKDOWN):
            continue
        if path in exempt:
            report.add(
                "error", "CG008", GUARD, 0,
                f"`{path}` was deleted; remove it from DOCS_BUDGET_OWNER_EXEMPT (invariant_guard fails on an "
                "exempt path that is not in the checkout).",
            )
        if path in rows:
            report.add(
                "warning", "CG008", GUARD, rows[path][1] + 1,
                f"`{path}` was deleted; remove its DOCS_BUDGET row and lower no other cap (AGENTS.md Docs policy).",
            )
        if path in inputs:
            report.add("error", "CG008", BUILDER, 0, f"`{path}` was deleted; remove it from INPUTS and regenerate {MANUAL}.")
        needle = reference_needle(path, remaining)
        if not needle:
            continue
        for holder in references(needle):
            if holder not in (GUARD, BUILDER, MANUAL) and holder not in deleted:
                report.add("warning", "CG008", holder, 0, f"still names `{needle}` from deleted `{path}`; relink or remove it.")


def check_self_manual(report, root):
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, "MANUAL.md")
        done = subprocess.run(
            [sys.executable, os.path.join(root, BUILDER), "--root", root, "--out", out],
            capture_output=True, text=True, check=False,
        )
        if done.returncode != 0:
            report.add("error", "CG002", BUILDER, 0, f"the generator failed: {done.stderr.strip()[-300:]}")
            return
        if not os.path.isfile(os.path.join(root, MANUAL)):
            report.add("error", "CG002", MANUAL, 0, "missing; the generator's output must be tracked.")
            return
        with open(out, "rb") as fresh, open(os.path.join(root, MANUAL), "rb") as tracked:
            if fresh.read() != tracked.read():
                report.add(
                    "error", "CG002", MANUAL, 0,
                    f"stale: an input changed. Run `python3 {BUILDER}` and commit the result.",
                )


def index_snapshot(tmp, changed):
    """Writes the index copy of each file the content checks read under `tmp`
    and returns that directory: the generator, its inputs, the manual, the
    guard and the changed Markdown. Everything, when the inputs are unknown."""
    inputs = re.search(r"^INPUTS = \[(.*?)^\]", git("show", f":{BUILDER}", check=False), re.M | re.S)
    if inputs:
        paths = {BUILDER, MANUAL, GUARD, *(text[1:-1] for text in STRING.findall(inputs.group(1)))}
        paths.update(path for path in changed if path.lower().endswith(MARKDOWN))
        selection = ["--", *sorted(paths)]
    else:
        selection = ["-a"]
    # -q: a path that is not in the index is left out, and the check that needs it says so.
    git("checkout-index", "-q", f"--prefix={tmp}{os.sep}", *selection, check=False)
    return tmp


def read_text(root, path):
    try:
        with open(os.path.join(root, path), encoding="utf-8", errors="replace") as handle:
            return handle.read()
    except OSError:
        return ""


def check_docs_budget(report, root, changed, guard_text):
    rows, unparsed = budget_table(guard_text)
    if not rows or unparsed:
        # Never go quiet: an unread table would pass every file and every raise.
        report.add(
            "error", "CG003", GUARD, 0,
            f"read {len(rows)} DOCS_BUDGET rows and could not read {unparsed}; fix ROW in scripts/lint-diff.py.",
        )
    folder = FOLDER_README_WORDS.search(guard_text)
    folder_words = int(folder.group(1).replace("_", "")) if folder else None
    for path in sorted(changed):
        if not path.lower().endswith(MARKDOWN):
            continue
        cap = cap_for(path, rows, folder_words)
        if cap is None or not os.path.isfile(os.path.join(root, path)):
            continue
        words = len(read_text(root, path).split())
        if words > cap:
            report.add("error", "CG003", path, 0, f"{words} words, cap {cap} in {GUARD} DOCS_BUDGET. Trim it; do not raise the cap.")


def check_cap_raises(report, base, guard_text, guard_added):
    old = git("show", f"{base}:{GUARD}", check=False)
    if not old:
        return
    before, lines = budget_rows(old), guard_text.splitlines()
    for path, (cap, index) in sorted(budget_rows(guard_text).items()):
        was = before.get(path, (None, 0))[0]
        if was is not None and cap <= was:
            continue
        change = f"raised from {was} to {cap}" if was is not None else f"new row at {cap}"
        fresh_why = [at for at in why_lines_above(lines, index) if at + 1 in guard_added]
        if fresh_why:
            report.add("warning", "CG004", GUARD, index + 1, f"`{path}` cap {change}: needs operator approval; name it in the PR body.")
        else:
            report.add("error", "CG004", GUARD, index + 1, f"`{path}` cap {change} with no new `// why:` comment directly above the row.")


def check_timing(report, added):
    for path, lines in sorted(added.items()):
        if not path.endswith(".rs"):
            continue
        for number, text in sorted(lines.items()):
            bound = ELAPSED_BOUND.search(code_part(text))
            if not bound or re.match(r"\s*while\b", text):
                continue
            value = int(bound.group(2).replace("_", ""))
            millis = value if bound.group(1) == "millis" else value * 1000
            if millis < TIMING_FLOOR_MS:
                report.add(
                    "warning", "CG005", path, number,
                    f"{millis} ms wall-clock bound: a busy runner fails it. Assert order or causality, or move "
                    "the bound an order of magnitude from the expected time.",
                )


CONFIG = "assets/config.default.yaml"
YAML_KEY = re.compile(r"^(?P<indent> *)(?P<key>[A-Za-z0-9_]+):(?:\s+(?P<value>.*?))?\s*$")
# A claim is a backticked key, then in the same clause `ships VALUE`, or
# `remains/stays VALUE` followed by "shipped"/"by default". Value-first
# phrasings ("ships closed: `agentic.enabled`") are not read.
CLAIM_KEY = r"`(?P<key>[a-z_][a-z0-9_]*(?:\.[a-z0-9_]+)*)`[^`.;:]{0,40}?"
CLAIM_VALUE = r"(?P<value>true|false|on|off|open|closed|enabled|disabled|`[^`\n]+`|-?\d+(?:\.\d+)?)(?!\w|\.\d)"
SHIPS_CLAIM = re.compile(CLAIM_KEY + r"\bships?\b(?:\s+as)?(?:\s+the)?(?:\s+literal)?(?:\s+boolean)?\s+" + CLAIM_VALUE)
STAYS_CLAIM = re.compile(
    CLAIM_KEY + r"\b(?:remains?|stays?)\s+" + CLAIM_VALUE + r"(?=[^.]{0,20}\b(?:shipped|by\s+default))"
)
TRUE_WORDS = ("true", "on", "open", "enabled")
FALSE_WORDS = ("false", "off", "closed", "disabled")


def yaml_scalar(text):
    if text in ("true", "false"):
        return text == "true"
    if text in ("null", "~"):
        return None
    if re.fullmatch(r"-?\d+", text):
        return int(text)
    if re.fullmatch(r"-?\d+\.\d+", text):
        return float(text)
    if len(text) >= 2 and text[0] == text[-1] and text[0] in "\"'":
        return text[1:-1]
    return text


def yaml_value(raw):
    """A key's value without its trailing comment; quotes protect a `#`."""
    closing = None
    for i, ch in enumerate(raw):
        if closing:
            if ch == closing:
                closing = None
        elif ch in "\"'":
            closing = ch
        elif ch == "#" and (i == 0 or raw[i - 1] in " \t"):
            return raw[:i].strip()
    return raw.strip()


def shipped_values(text):
    """{dotted.path: scalar} for every block-style scalar in the shipped YAML.
    Lists, flow collections and block strings are skipped, never guessed."""
    values, stack = {}, []
    for line in text.splitlines():
        stripped = line.lstrip()
        if not stripped or stripped.startswith(("#", "-")):
            continue
        entry = YAML_KEY.match(line)
        if not entry:
            continue
        indent = len(entry.group("indent"))
        while stack and stack[-1][0] >= indent:
            stack.pop()
        value = yaml_value(entry.group("value") or "")
        path = ".".join([key for _, key in stack] + [entry.group("key")])
        if not value:
            stack.append((indent, entry.group("key")))
        elif not value.startswith(("[", "{", "|", ">", "&", "*", "!")):
            values[path] = yaml_scalar(value)
    return values


def claimed(value):
    if value.startswith("`"):
        inner = value[1:-1]
        return yaml_scalar(inner) if inner in ("true", "false") or re.fullmatch(r"-?\d+(?:\.\d+)?", inner) else inner
    if value in TRUE_WORDS:
        return True
    if value in FALSE_WORDS:
        return False
    return yaml_scalar(value)


def agrees(said, shipped):
    """True or False when the two are comparable, else None (skipped)."""
    if isinstance(said, bool) or isinstance(shipped, bool):
        return said is shipped if isinstance(said, bool) and isinstance(shipped, bool) else None
    if isinstance(said, (int, float)) and isinstance(shipped, (int, float)):
        return float(said) == float(shipped)
    if isinstance(said, str) and isinstance(shipped, str):
        return said == shipped
    return None


def resolve_key(key, values):
    """(path, exact): the key itself, or the one shipped path it ends."""
    if key in values:
        return key, True
    ends = [path for path in values if path.endswith("." + key)]
    return (ends[0], False) if len(ends) == 1 else (None, False)


def shipped_claims(text):
    """(line, key, value) for each claim. Paragraphs are joined first, so a
    claim wrapped across lines is read; the line is the value's."""
    lines, index = text.splitlines(), 0
    while index < len(lines):
        if not lines[index].strip():
            index += 1
            continue
        end, starts, offset = index, [], 0
        while end < len(lines) and lines[end].strip():
            starts.append(offset)
            offset += len(lines[end]) + 1
            end += 1
        paragraph = " ".join(lines[index:end])
        for pattern in (SHIPS_CLAIM, STAYS_CLAIM):
            for claim in pattern.finditer(paragraph):
                at = claim.start("value")
                line = index + max(i for i, start in enumerate(starts) if start <= at) + 1
                yield line, claim.group("key"), claim.group("value")
        index = end


def check_shipped_claims(report, values, documents, keys=None, lines_of=None, skip=frozenset()):
    """`documents` maps path -> text. Only claims on `lines_of[path]` (added
    lines) are checked when it is given, only claims about `keys` (the paths
    whose shipped value changed) when that is given, and never claims about
    `skip` (checked by the other pass)."""
    for path, text in sorted(documents.items()):
        if path == MANUAL:
            continue
        for line, key, value in shipped_claims(text):
            if lines_of is not None and line not in lines_of.get(path, ()):
                continue
            target, exact = resolve_key(key, values)
            if target is None or target in skip or (keys is not None and target not in keys):
                continue
            if agrees(claimed(value), values[target]) is False:
                shipped = values[target]
                shown = str(shipped).lower() if isinstance(shipped, bool) else shipped
                report.add(
                    "error" if exact else "warning", "CG009", path, line,
                    f"says `{key}` ships {value}, but {CONFIG} ships `{target}: {shown}`. "
                    "Fix the prose (or the config) in this change.",
                )


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    scope = parser.add_mutually_exclusive_group()
    scope.add_argument("--base", help="compare against this ref (default: merge base with origin/main)")
    scope.add_argument("--staged", action="store_true", help="check what is staged for the next commit")
    args = parser.parse_args()

    root = git("rev-parse", "--show-toplevel").strip()
    os.chdir(root)
    if args.staged:
        base, diff_args = "HEAD", ["--cached"]
    else:
        ref = args.base or "origin/main"
        base = git("merge-base", ref, "HEAD", check=False).strip()
        if not base:
            sys.stderr.write(f"lint-diff: no merge base with {ref}; fetch it or pass --base REF.\n")
            return 2
        diff_args = [base]

    added = added_lines(diff_args)
    deleted = set(git("diff", "--name-only", "--no-renames", "--diff-filter=D", *diff_args).split("\n")) - {""}
    changed = set(git("diff", "--name-only", "--no-renames", "--diff-filter=AM", *diff_args).split("\n")) - {""}
    if not args.staged:
        # `git diff` cannot see a file that was never added; it is still part of the branch.
        for path in git("ls-files", "--others", "--exclude-standard").splitlines():
            changed.add(path)
            if os.path.splitext(path)[1] in DIGEST_LANGUAGES:
                with open(os.path.join(root, path), encoding="utf-8", errors="replace") as handle:
                    added[path] = dict(enumerate(handle.read().splitlines(), 1))

    report = Report()
    with tempfile.TemporaryDirectory() as tmp:
        # Where file content is read: the pending commit for --staged, else the working tree.
        content = index_snapshot(tmp, changed) if args.staged else root
        guard_text = read_text(content, GUARD)
        check_devskim(report, added)
        check_self_manual(report, content)
        check_docs_budget(report, content, changed, guard_text)
        check_cap_raises(report, base, guard_text, added.get(GUARD, {}))
        # CG009: shipped values against the prose that states them.
        values = shipped_values(read_text(content, CONFIG) if not args.staged else git("show", f":{CONFIG}", check=False))
        markdown = {path for path in changed if path.lower().endswith(MARKDOWN)}
        added_markdown = {
            path: (set(added[path]) if path in added else set(range(1, read_text(root, path).count("\n") + 2)))
            for path in markdown
        }
        before = shipped_values(git("show", f"{base}:{CONFIG}", check=False))
        moved = {path for path, value in values.items() if path in before and before[path] != value}
        check_shipped_claims(
            report, values, {path: read_text(content, path) for path in markdown}, lines_of=added_markdown, skip=moved
        )
        if moved:
            # Every tracked Markdown file, changed ones included: an untouched
            # line still states the old value.
            listed = git("ls-files", *(["--cached"] if args.staged else []), "--", *(f"*{ext}" for ext in MARKDOWN))
            documents = {
                path: (read_text(content, path) if path in markdown else
                       git("show", f":{path}", check=False) if args.staged else read_text(root, path))
                for path in listed.splitlines()
                if path
            }
            check_shipped_claims(report, values, documents, keys=moved)
        check_timing(report, added)
        check_weak_hashes(report, added)
        check_password_literals(report, added)
        check_assert_messages(report, added, lambda path: read_text(content, path))
        grep_scope = ["--cached"] if args.staged else []

        def references(needle):
            found = git("grep", "-l", "-F", *grep_scope, "-e", needle, check=False)
            return [line for line in found.splitlines() if line]

        tracked = git("ls-files", "--cached", check=False).splitlines()
        check_deleted_docs(report, deleted, guard_text, read_text(content, BUILDER), references, tracked)
    print(f"lint-diff: {report.errors} error(s), {report.warnings} warning(s) against {base[:12]}")
    return 1 if report.errors else 0


if __name__ == "__main__":
    sys.exit(main())
